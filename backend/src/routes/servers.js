// Channel ids are not auto-generated by Prisma (the model has no @default),
// so we mint a collision-resistant id ourselves. The old
// `Math.random().toString(36).substring(7)` produced 0–6 char ids that could
// be empty or collide, breaking channel creation under load.
function newChannelId() {
  return crypto.randomUUID();
}

// Discord-style boost level from a raw boost count.
function boostLevelFromCount(n) {
  if (n >= 14) return 3;
  if (n >= 7) return 2;
  if (n >= 2) return 1;
  return 0;
}

// Fetch servers the user is a member of
// Supports ?members=offset,limit query param for lazy-loading members.
// Default: first 50 members included. Additional members via the query param.

// Rate limiting
serverRouter.use(rateLimit);

serverRouter.get('/servers', requireAuth, async (req, res, next) => {
  try {
    const membersParam = req.query.members;
    let memberSkip = 0;
    let memberTake = 50;
    if (membersParam) {
      const parts = String(membersParam).split(',').map(Number);
      if (parts.length === 2 && Number.isFinite(parts[0]) && Number.isFinite(parts[1])) {
        memberSkip = Math.max(0, parts[0]);
        memberTake = Math.min(Math.max(1, parts[1]), 100);
      }
    }

    const servers = await prisma.server.findMany({
      where: { members: { some: { userId: req.user.id } } },
      include: {
        channels: true,
        members: {
          include: { user: true },
          skip: memberSkip,
          take: memberTake,
          orderBy: { joinedAt: 'asc' },
        },
      },
    });
    // Self-heal: servers created before voice-channel seeding (or where every
    // voice channel was deleted) get a fresh General voice channel so the
    // sidebar never shows a dead "NO VOICE CHANNELS" section.
    //
    // Runs inside a transaction with FOR UPDATE row locks so two concurrent
    // GET /servers calls can never both create a duplicate voice channel.
    const healed = await prisma.$transaction(async (tx) => {
      const missing = servers.filter((s) => !s.channels.some((c) => c.type === 'VOICE'));
      const created = [];
      for (const s of missing) {
        await tx.$queryRaw`SELECT id FROM "Server" WHERE id = ${s.id} FOR UPDATE`;
        const count = await tx.channel.count({ where: { serverId: s.id, type: 'VOICE' } });
        if (count === 0) {
          created.push({
            serverId: s.id,
            channel: await tx.channel.create({
              data: { id: newChannelId(), name: 'General', type: 'VOICE', serverId: s.id },
            }),
          });
        }
      }
      return created;
    });
    // Attach the real created channels so the response reflects the healing
    // without a second query.
    for (const { serverId, channel } of healed) {
      const s = servers.find((x) => x.id === serverId);
      if (s) s.channels.push(channel);
    }
    res.json(servers);
  } catch (e) { next(e); }
});

// Create a server
serverRouter.post('/servers', requireAuth, async (req, res, next) => {
  try {
    const { name, description, icon } = req.body;
    if (!name) throw new HttpError(400, 'Server name is required');

    const server = await prisma.server.create({
      data: {
        name,
        description,
        icon,
        ownerId: req.user.id,
        members: {
          create: [{ userId: req.user.id, role: 'FOUNDER' }]
        },
        channels: {
          // Discord-style seed: a text #general plus a General voice channel,
          // so a fresh server is never stuck in "NO VOICE CHANNELS".
          create: [
            { id: newChannelId(), name: 'general', type: 'TEXT' },
            { id: newChannelId(), name: 'General', type: 'VOICE' }
          ]
        }
      },
      include: { channels: true, members: { include: { user: true } } }
    });

    res.status(201).json({ server });
  } catch (e) { next(e); }
});

// Create a channel
serverRouter.post('/servers/:id/channels', requireAuth, async (req, res, next) => {
  try {
    const serverId = req.params.id;
    const { name, type, region, rtcMode, maxParticipants } = req.body;
    if (!name) throw new HttpError(400, 'Channel name is required');

    const server = await prisma.server.findUnique({ where: { id: serverId } });
    if (!server) throw new HttpError(404, 'Server not found');

    const member = await prisma.serverMember.findUnique({
      where: { serverId_userId: { serverId, userId: req.user.id } },
    });
    if (!member || (member.role !== 'FOUNDER' && member.role !== 'ADMIN')) {
      throw new HttpError(403, 'Not authorized');
    }

    const data = {
      id: newChannelId(),
      name: name.trim().toLowerCase().replace(/\s+/g, '-').slice(0, 50) || 'general',
      type: type === 'VOICE' ? 'VOICE' : type === 'STAGE' ? 'STAGE' : type === 'FORUM' ? 'FORUM' : 'TEXT',
      serverId,
    };
    if (typeof region === 'string' && region) data.region = region.slice(0, 32);
    if (rtcMode === 'MESH' || rtcMode === 'SFU') data.rtcMode = rtcMode;
    else if (data.type === 'STAGE') data.rtcMode = 'SFU';
    if (typeof maxParticipants === 'number') {
      data.maxParticipants = Math.min(Math.max(0, Math.floor(maxParticipants)), 1000);
    }

    const channel = await prisma.channel.create({ data });

    res.status(201).json({ channel });
  } catch (e) { next(e); }
});

// Add a member directly by username. Founder/Admin only.
serverRouter.post('/servers/:id/members', requireAuth, async (req, res, next) => {
  try {
    const serverId = req.params.id;
    const username = String(req.body?.username || '').trim();
    if (!username) throw new HttpError(400, 'Username is required');

    const member = await prisma.serverMember.findUnique({
      where: { serverId_userId: { serverId, userId: req.user.id } },
    });
    if (!member || !['FOUNDER', 'ADMIN'].includes(member.role)) {
      throw new HttpError(403, 'Only admins may add members.');
    }

    const user = await prisma.user.findUnique({ where: { username } });
    if (!user) throw new HttpError(404, 'User not found.');

    const existing = await prisma.serverMember.findUnique({
      where: { serverId_userId: { serverId, userId: user.id } },
    });
    if (existing) {
      const server = await prisma.server.findUnique({
        where: { id: serverId },
        include: { channels: true, members: { include: { user: true } } },
      });
      return res.json({ server, alreadyMember: true });
    }

    await prisma.serverMember.create({
      data: { serverId, userId: user.id, role: 'MEMBER' },
    });
    const server = await prisma.server.findUnique({
      where: { id: serverId },
      include: { channels: true, members: { include: { user: true } } },
    });
    res.status(201).json({ server, member: user, alreadyMember: false });
  } catch (e) { next(e); }
});

// Delete a server
serverRouter.delete('/servers/:id', requireAuth, async (req, res, next) => {
  try {
    const serverId = req.params.id;
    const server = await prisma.server.findUnique({ where: { id: serverId } });
    if (!server) throw new HttpError(404, 'Server not found');
    if (server.ownerId !== req.user.id) throw new HttpError(403, 'Only owner can delete server');

    // Capture the member list BEFORE deletion so we can tell their live
    // clients to drop the dead server from their sidebar. Without this a
    // server-deleted event lands on already-deleted Channel rows (cascade
    // already ran) so we emit the membership snapshot through the realtime
    // bridge — socket-broadcasting a server list refresh is the friendliest
    // UX and avoids the "stale server in my sidebar" loop.
    const memberIds = (await prisma.serverMember.findMany({
      where: { serverId },
      select: { userId: true },
    })).map((m) => m.userId);

    await prisma.server.delete({ where: { id: serverId } });

    // Tell every connected client to drop this server id from any local
    // cache. Real-time events are best-effort — failure to broadcast doesn't
    // roll back the database delete.
    try {
      const io = getIO();
      if (io) io.emit('server:deleted', { serverId, memberIds });
    } catch (emitErr) {
      console.warn('[servers] Failed to broadcast server:deleted', emitErr);
    }

    res.json({ message: 'Server deleted' });
  } catch (e) { next(e); }
});

// Boost / unboost a server (any member). Tracks booster user IDs in the
// `boosters` JSON array to prevent double-counting. Mirrors Discord's
// server-boosting mechanic and drives the computed boost level.
serverRouter.post('/servers/:id/boost', requireAuth, async (req, res, next) => {
  try {
    const serverId = req.params.id;
    const member = await prisma.serverMember.findUnique({
      where: { serverId_userId: { serverId, userId: req.user.id } },
    });
    if (!member) throw new HttpError(403, 'You must be a member to boost this server.');

    const server = await prisma.server.findUnique({ where: { id: serverId } });
    if (!server) throw new HttpError(404, 'Server not found.');

    const boosters = Array.isArray(server.boosters) ? server.boosters : [];
    if (boosters.includes(req.user.id)) {
      return res.json({ boosted: true, boosts: server.boosts, boostLevel: boostLevelFromCount(server.boosts) });
    }
    const updated = await prisma.server.update({
      where: { id: serverId },
      data: { boosts: { increment: 1 }, boosters: [...boosters, req.user.id] },
    });
    res.json({ boosted: true, boosts: updated.boosts, boostLevel: boostLevelFromCount(updated.boosts) });
  } catch (e) { next(e); }
});

serverRouter.post('/servers/:id/unboost', requireAuth, async (req, res, next) => {
  try {
    const serverId = req.params.id;
    const server = await prisma.server.findUnique({ where: { id: serverId } });
    if (!server) throw new HttpError(404, 'Server not found.');

    const boosters = Array.isArray(server.boosters) ? server.boosters : [];
    if (!boosters.includes(req.user.id)) {
      return res.json({ boosted: false, boosts: server.boosts, boostLevel: boostLevelFromCount(server.boosts) });
    }
    const updated = await prisma.server.update({
      where: { id: serverId },
      data: {
        boosts: { decrement: 1 },
        boosters: boosters.filter((id) => id !== req.user.id),
      },
    });
    res.json({ boosted: false, boosts: Math.max(0, updated.boosts), boostLevel: boostLevelFromCount(Math.max(0, updated.boosts)) });
  } catch (e) { next(e); }
});

