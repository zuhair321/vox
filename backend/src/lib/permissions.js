export function hasPermission(permissions, permission) {
  return (permissions & Permissions[permission]) === Permissions[permission];
}

export function combinePermissions(...perms) {
  return perms.reduce((acc, p) => acc | Permissions[p], 0n);
}

export function permissionNames(permissions) {
  return Object.entries(Permissions)
    .filter(([, bit]) => (permissions & bit) === bit)
    .map(([name]) => name);
}

