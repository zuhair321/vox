#!/bin/bash
# ═══════════════════════════════════════════════════════════════
# VOX — Oracle Cloud Free Tier Automated Deploy Script
# ═══════════════════════════════════════════════════════════════
# Run on a fresh Ubuntu 22.04/24.04 Oracle Cloud Ampere A1 instance.
#
# Usage:
#   chmod +x deploy.sh
#   sudo ./deploy.sh
#
# What it does:
#   1. Installs Docker, Docker Compose, Certbot
#   2. Clones VOX from GitHub (or uses local copy)
#   3. Generates all secrets automatically
#   4. Configures firewall (UFW)
#   5. Builds and starts the full stack
#   6. Obtains SSL certificate via Let's Encrypt
#   7. Sets up automatic renewal
# ═══════════════════════════════════════════════════════════════

set -euo pipefail

# ── Colors ────────────────────────────────────────────────────
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

log()  { echo -e "${BLUE}[VOX]${NC} $1"; }
ok()   { echo -e "${GREEN}[✓]${NC} $1"; }
warn() { echo -e "${YELLOW}[!]${NC} $1"; }
err()  { echo -e "${RED}[✗]${NC} $1"; exit 1; }

# ── Check root ───────────────────────────────────────────────
if [[ $EUID -ne 0 ]]; then
    err "This script must be run as root. Use: sudo ./deploy.sh"
fi

# ── Gather configuration ─────────────────────────────────────
echo ""
echo -e "${BLUE}═══════════════════════════════════════════════════════════${NC}"
echo -e "${BLUE}  VOX — Oracle Cloud Free Tier Deployment${NC}"
echo -e "${BLUE}═══════════════════════════════════════════════════════════${NC}"
echo ""

read -p "Domain name (e.g. vox.yourdomain.com): " DOMAIN
read -p "Email for Let's Encrypt: " EMAIL
read -p "PostgreSQL password: " PG_PASSWORD
read -p "GitHub repo URL (or press Enter for local): " REPO_URL

if [[ -z "$REPO_URL" ]]; then
    REPO_URL="https://github.com/zuhair321/vox.git"
fi

# ── Generate secrets ─────────────────────────────────────────
log "Generating cryptographic secrets..."
JWT_ACCESS=$(openssl rand -hex 48)
JWT_REFRESH=$(openssl rand -hex 48)
TFA_KEY=$(openssl rand -hex 32)

ok "Secrets generated"

# ── Install dependencies ─────────────────────────────────────
log "Installing Docker..."
if ! command -v docker &> /dev/null; then
    curl -fsSL https://get.docker.com | bash
    systemctl enable --now docker
    ok "Docker installed"
else
    ok "Docker already installed"
fi

log "Installing Docker Compose plugin..."
if ! docker compose version &> /dev/null; then
    apt-get update && apt-get install -y docker-compose-plugin
    ok "Docker Compose installed"
else
    ok "Docker Compose already installed"
fi

log "Installing Certbot..."
if ! command -v certbot &> /dev/null; then
    apt-get update && apt-get install -y certbot
    ok "Certbot installed"
else
    ok "Certbot already installed"
fi

# ── Clone or use local repo ──────────────────────────────────
DEPLOY_DIR="/opt/vox"
if [[ -d "$DEPLOY_DIR" ]]; then
    warn "Directory $DEPLOY_DIR already exists — using it"
else
    log "Cloning VOX repository..."
    git clone "$REPO_URL" "$DEPLOY_DIR"
    ok "Repository cloned"
fi

cd "$DEPLOY_DIR"

# ── Create .env ──────────────────────────────────────────────
log "Creating production .env file..."
cat > .env << EOF
# VOX Production Environment — Auto-generated by deploy.sh
# Generated: $(date -u +"%Y-%m-%d %H:%M:%S UTC")

POSTGRES_DB=vox_prod
POSTGRES_USER=vox
POSTGRES_PASSWORD=$PG_PASSWORD

JWT_ACCESS_SECRET=$JWT_ACCESS
JWT_REFRESH_SECRET=$JWT_REFRESH
JWT_ACCESS_TTL=30m
JWT_REFRESH_TTL=14d

TWO_FACTOR_APP_NAME=VOX
TWO_FACTOR_ENCRYPTION_KEY=$TFA_KEY

NODE_ENV=production
PORT=4000
CLIENT_ORIGIN=https://$DOMAIN
EXTRA_CORS_ORIGINS=

RESEND_API_KEY=dev
RESEND_FROM_ADDRESS="VOX <noreply@$DOMAIN>"

RATE_LIMIT_WINDOW_MS=60000
RATE_LIMIT_MAX_REQUESTS=100

DOMAIN=$DOMAIN
EMAIL=$EMAIL
EOF

ok ".env created"

# ── Configure firewall ───────────────────────────────────────
log "Configuring UFW firewall..."
if command -v ufw &> /dev/null; then
    ufw allow 22/tcp    # SSH
    ufw allow 80/tcp    # HTTP
    ufw allow 443/tcp   # HTTPS
    ufw --force enable
    ok "Firewall configured"
else
    warn "UFW not found — ensure ports 80 and 443 are open in Oracle Cloud Security List"
fi

# ── Build and start ──────────────────────────────────────────
log "Building Docker images (this may take 5-10 minutes)..."
docker compose build --no-cache

log "Starting services..."
docker compose up -d

# Wait for backend to be healthy
log "Waiting for backend to become healthy..."
for i in $(seq 1 60); do
    if docker compose exec -T backend curl -sf http://localhost:4000/health > /dev/null 2>&1; then
        ok "Backend is healthy!"
        break
    fi
    if [[ $i -eq 60 ]]; then
        err "Backend failed to start within 60 seconds. Check: docker compose logs backend"
    fi
    sleep 2
done

# ── SSL Certificate ──────────────────────────────────────────
log "Obtaining SSL certificate from Let's Encrypt..."
# First, temporarily serve on port 80 without SSL
docker compose exec -T nginx sh -c "sed -i 's/ssl_certificate/#ssl_certificate/g; s/ssl_certificate_key/#ssl_certificate_key/g; s/listen 443/#listen 443/g; s/listen \[::\]:443/#listen [::]:443/g' /etc/nginx/conf.d/default.conf && nginx -s reload" 2>/dev/null || true

# Get the certificate
certbot certonly --webroot \
    --webroot-path=/var/www/html \
    --email "$EMAIL" \
    --agree-tos \
    --no-eff-email \
    -d "$DOMAIN"

# Update nginx config to use the real certificate
docker compose exec -T nginx sed -i "s/vox.example.com/$DOMAIN/g" /etc/nginx/conf.d/default.conf
docker compose exec -T nginx sh -c "sed -i 's/#ssl_certificate/ssl_certificate/g; s/#ssl_certificate_key/ssl_certificate_key/g; s/#listen 443/listen 443/g; s/#listen \[::\]:443/listen [::]:443/g' /etc/nginx/conf.d/default.conf && nginx -s reload"

ok "SSL certificate installed"

# ── Auto-renewal ─────────────────────────────────────────────
log "Setting up SSL auto-renewal..."
cat > /etc/cron.d/vox-ssl-renew << 'EOF'
# Renew VOX SSL certificate twice daily
0 3,15 * * * root certbot renew --quiet --deploy-hook "docker compose -f /opt/vox/docker-compose.yml exec -T nginx nginx -s reload" >> /var/log/vox-ssl-renew.log 2>&1
EOF

ok "Auto-renewal configured"

# ── Print summary ────────────────────────────────────────────
echo ""
echo -e "${GREEN}═══════════════════════════════════════════════════════════${NC}"
echo -e "${GREEN}  VOX Deployment Complete!${NC}"
echo -e "${GREEN}═══════════════════════════════════════════════════════════${NC}"
echo ""
echo -e "  URL:        ${BLUE}https://$DOMAIN${NC}"
echo -e "  Health:     ${BLUE}https://$DOMAIN/health${NC}"
echo -e "  Logs:       ${BLUE}docker compose logs -f${NC}"
echo -e "  Restart:    ${BLUE}docker compose restart${NC}"
echo -e "  Stop:       ${BLUE}docker compose down${NC}"
echo ""
echo -e "  Backend:    ${GREEN}running${NC} on :4000"
echo -e "  PostgreSQL: ${GREEN}running${NC} on :5432"
echo -e "  Redis:      ${GREEN}running${NC} on :6379"
echo -e "  Nginx:      ${GREEN}running${NC} on :80/:443"
echo -e "  SSL:        ${GREEN}active${NC} (auto-renews)"
echo ""
echo -e "  Data dir:   /opt/vox"
echo -e "  Uploads:    Docker volume 'vox_uploads_data'"
echo ""
echo -e "${YELLOW}  Save this somewhere safe:${NC}"
echo -e "  PG Password:     $PG_PASSWORD"
echo -e "  JWT Access:      ${JWT_ACCESS:0:16}..."
echo -e "  2FA Key:         ${TFA_KEY:0:16}..."
echo ""
echo -e "${GREEN}═══════════════════════════════════════════════════════════${NC}"
